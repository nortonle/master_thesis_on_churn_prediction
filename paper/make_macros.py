"""Regenerate the paper's numbers from the notebook's result tables.

Usage:  python make_macros.py [results_dir]      (default: the parent folder)

Writes, next to this script:
  results_macros.tex   scalar macros used in the prose
  tab_*.tex            table bodies that main.tex \\input's
  figures/             copies of the figures the paper uses
"""
import os
import shutil
import sys

import numpy as np
import pandas as pd

HERE = os.path.dirname(os.path.abspath(__file__))
SRC = os.path.abspath(sys.argv[1]) if len(sys.argv) > 1 else os.path.dirname(HERE)


def read(name, **kw):
    return pd.read_csv(os.path.join(SRC, f"results_v2_{name}.csv"), **kw)


facts = read("study_facts").set_index("item")["value"]
test = read("test_set_results")
hw = read("hardware").set_index("item")["value"]
ver = read("library_versions").set_index("library")["version"]
dev = read("device_benchmark")
conc = read("concurrency_benchmark").set_index("model")
stages = {k: read(f"experiment_{k}").set_index("model") for k in "abc"}
fe = read("feature_engineering_effect").set_index("model")
tune = read("tuning_effect").set_index("model")
hpo = read("hyperparameter_search")
abl = read("imbalance_ablation")

SHORT = {"LogisticRegression": "LR", "DecisionTree": "DT", "RandomForest": "RF",
         "XGBoost": "XGB", "ANN": "ANN", "DNN": "DNN"}
LONG = {"LogisticRegression": "logistic regression", "DecisionTree": "a decision tree",
        "RandomForest": "a random forest", "XGBoost": "XGBoost",
        "ANN": "the shallow network", "DNN": "the deep network"}
ORDER = ["LogisticRegression", "DecisionTree", "RandomForest", "XGBoost", "ANN", "DNN"]

champ = facts["champion_name"]
t = test.set_index("model")
dl = test[test.family == "DL"].sort_values("roc_auc", ascending=False)
best_dl = dl.model.iloc[0]
exp_letter = facts["champion_experiment"][0]
champ_desc = {"A": "at default settings on the raw features",
              "B": "at default settings on the engineered features",
              "C": "tuned, on the engineered features"}[exp_letter]

M = {}
M["NRows"] = f"{int(float(facts['n_rows'])):,}"
M["NCols"] = f"{int(float(facts['n_cols']))}"
M["NTrain"] = f"{int(float(facts['n_train'])):,}"
M["NTest"] = f"{int(float(facts['n_test'])):,}"
M["NDev"] = f"{int(float(facts['n_dev'])):,}"
M["NTune"] = f"{int(float(facts['n_tune'])):,}"
M["ChurnRatePct"] = f"{100 * float(facts['churn_rate']):.2f}"
M["ImbRatio"] = f"{float(facts['imbalance_ratio']):.1f}"
M["NEngineered"] = {23: "Twenty-three", 24: "Twenty-four", 25: "Twenty-five"}.get(
    int(float(facts["n_engineered_derived"])), str(int(float(facts["n_engineered_derived"]))))
M["NBaseline"] = f"{int(float(facts['n_baseline']))}"
M["NEngSet"] = f"{int(float(facts['n_engineered_set']))}"
M["McDraws"] = f"{int(float(facts['mc_draws'])):,}"
M["CampaignSharePct"] = f"{100 * float(facts['campaign_share']):.0f}"
M["ChampionLong"] = f"{LONG[champ]} {champ_desc}"
M["ChampionShort"] = SHORT[champ]
M["BestDlShort"] = SHORT[best_dl]
M["ChampAucTest"] = f"{t.loc[champ, 'roc_auc']:.4f}"
M["BestDlAucTest"] = f"{t.loc[best_dl, 'roc_auc']:.4f}"
M["TestAucMin"] = f"{test.roc_auc.min():.3f}"
M["TestAucMax"] = f"{test.roc_auc.max():.3f}"
M["TestSpread"] = f"{test.roc_auc.max() - test.roc_auc.min():.3f}"
M["TrainRatioBestDl"] = f"{t.loc[best_dl, 'train_seconds_full'] / t.loc[champ, 'train_seconds_full']:.0f}"
M["ChampOnlineMs"] = f"{t.loc[champ, 'online_p50_ms']:.1f}"
M["BestDlOnlineMs"] = f"{t.loc[best_dl, 'online_p50_ms']:.1f}"
piv = dev.pivot(index="model", columns="device", values="seconds_per_epoch")
gpu_col = [c for c in piv.columns if c != "CPU"]
if gpu_col:
    slow = piv[gpu_col[0]] / piv["CPU"]
    M["GpuSlowdownDnn"] = f"{slow['DNN']:.1f}"
    M["GpuSlowdownAnn"] = f"{slow['ANN']:.1f}"
else:
    M["GpuSlowdownDnn"] = M["GpuSlowdownAnn"] = "n/a"
M["HwChip"] = str(hw.get("chip", "n/a"))
M["HwCores"] = str(hw["logical_cores"])
M["HwRam"] = f"{float(hw['ram_gb']):.0f}"
M["HwOs"] = str(hw["platform"]).split("-arm64")[0].replace("-", " ")
M["TfVersion"] = ver["tensorflow"]
M["MetalVersion"] = ver["tensorflow-metal"]
M["SkVersion"] = ver["sklearn"]
M["XgbVersion"] = ver["xgboost"]
M["OptunaVersion"] = ver["optuna"]
M["ShapVersion"] = ver["shap"]

with open(os.path.join(HERE, "results_macros.tex"), "w") as fh:
    fh.write("% Generated by make_macros.py -- do not edit by hand.\n")
    fh.write(f"% Source: {os.path.basename(SRC)} | quick_run = {facts.get('quick_run')}\n")
    for k, v in M.items():
        fh.write(f"\\newcommand{{\\{k}}}{{{v}}}\n")


def write(name, lines):
    # The last row carries no "\\": main.tex supplies it after \input, because LaTeX's
    # \input is not expandable and a rule placed directly after it raises "Misplaced \noalign".
    lines = list(lines)
    lines[-1] = lines[-1].rstrip().removesuffix("\\\\").rstrip()
    with open(os.path.join(HERE, name), "w") as fh:
        fh.write("% Generated by make_macros.py -- do not edit by hand.\n" + "\n".join(lines) + "\n")


def star(p):
    return "$^{*}$" if p < 0.05 else ""


# ---- Table: three staged experiments --------------------------------------
rows = []
for m in ORDER:
    a, b = stages["a"].loc[m, "roc_auc"], stages["b"].loc[m, "roc_auc"]
    c = f"{stages['c'].loc[m, 'roc_auc']:.4f}" if m in stages["c"].index else "--"
    d_fe = f"{fe.loc[m, 'delta']:+.4f}{star(fe.loc[m, 'ttest_p'])}"
    d_tu = f"{tune.loc[m, 'delta']:+.4f}{star(tune.loc[m, 'ttest_p'])}" if m in tune.index else "--"
    rows.append(f"{SHORT[m]} & {a:.4f} & {b:.4f} & {c} & {d_fe} & {d_tu} \\\\")
write("tab_stages.tex", rows)

# ---- Table: imbalance ablation by family ----------------------------------
g = abl.groupby(["imbalance", "family"], observed=True)[["roc_auc", "recall"]].mean()
names = {"none": "None", "balanced": "Class weighting", "smote": "SMOTE", "ctgan": "CTGAN"}
rows = []
for arm in ["none", "balanced", "smote", "ctgan"]:
    if arm not in g.index.get_level_values(0):
        continue
    cells = []
    for fam in ["ML", "DL"]:
        cells += [f"{g.loc[(arm, fam), 'roc_auc']:.3f}", f"{g.loc[(arm, fam), 'recall']:.3f}"]
    rows.append(f"{names[arm]} & " + " & ".join(cells) + " \\\\")
write("tab_imbalance.tex", rows)

# ---- Table: search strategies ---------------------------------------------
rows = []
for m in ORDER[:4]:
    sub = hpo[hpo.model == m].set_index("strategy")
    best = sub.best_cv_auc.idxmax()
    cells = []
    for s in ["GridSearch", "RandomSearch", "Optuna"]:
        v = f"{sub.loc[s, 'best_cv_auc']:.4f}"
        cells.append(f"\\textbf{{{v}}}" if s == best else v)
    cells += [f"{sub.loc[s, 'search_seconds']:.0f}" for s in ["GridSearch", "RandomSearch", "Optuna"]]
    rows.append(f"{SHORT[m]} & " + " & ".join(cells) + " \\\\")
write("tab_hpo.tex", rows)

# ---- Table: held-out test results -----------------------------------------
rows = []
for _, r in test.sort_values("roc_auc", ascending=False).iterrows():
    cfg = r.configuration.split(" ")[0]
    name = SHORT[r.model] + ("$^{\\dagger}$" if r.model == champ else "")
    rows.append(f"{name} & {cfg} & {r.roc_auc:.4f} & {r.pr_auc:.4f} & {r.f1:.3f} & "
                f"{r.recall:.3f} & {r.precision:.3f} & {r.accuracy:.3f} \\\\")
write("tab_test.tex", rows)

# ---- Table: execution cost -------------------------------------------------
rows = []
for _, r in test.sort_values("roc_auc", ascending=False).iterrows():
    spe = "--" if pd.isna(r.get("seconds_per_epoch", np.nan)) else f"{r.seconds_per_epoch:.1f}"
    device = "GPU" if str(r.get("device", "CPU")).startswith("GPU") else "CPU"
    c = conc.loc[r.model]
    rows.append(f"{SHORT[r.model]} & {device} & {r.train_seconds_full:.0f} & {spe} & "
                f"{1000 * r.infer_ms_per_sample:.1f} & {r.online_p50_ms:.1f} & "
                f"{c['p50_ms_w8']:.0f} & {c['rps_w8']:.0f} \\\\")
write("tab_runtime.tex", rows)

# ---- Table: device benchmark ----------------------------------------------
rows = []
for _, r in dev.sort_values(["model", "device"]).iterrows():
    rows.append(f"{r.model} & {'GPU' if r.device != 'CPU' else 'CPU'} & {r.seconds_per_epoch:.2f} & "
                f"{1000 * r.infer_ms_per_sample:.1f} & {r.online_p50_ms:.1f} \\\\")
write("tab_device.tex", rows)

# ---- Figures ----------------------------------------------------------------
os.makedirs(os.path.join(HERE, "figures"), exist_ok=True)
for f in ["fig_9_2_forest", "fig_11_2_test_curves", "fig_8_2_performance_vs_time",
          "fig_10_1_shap_global", "fig_4_1_device_benchmark", "fig_11_4_concurrency", "fig_13_3_learning_curves"]:
    src = os.path.join(SRC, "figures_v2", f + ".png")
    if os.path.exists(src):
        shutil.copy(src, os.path.join(HERE, "figures", f + ".png"))

print(f"macros: {len(M)} | champion: {champ} [{exp_letter}] | best DL: {best_dl} | source: {SRC}")
